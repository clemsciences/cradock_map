#!/usr/bin/env python3
"""Generates light previews of the images shown in the app.

The originals (often several MB) are kept for the full-screen view and the
download; the pages display the previews, whose size is known in advance so
that the layout appears immediately.

Usage (from the project root, needs Pillow):
    python3 tool/make_previews.py
Handles the assets/focus/<folder>/ folders listed in pubspec.yaml and the
EXTRA_IMAGES below. Writes:
  - assets/previews/<original path without "assets/">, max MAX_SIZE px;
  - lib/data/image_previews.dart (generated, do not edit);
  - the matching assets/previews/... entries in pubspec.yaml.
Run it again after adding images or a new focus folder to pubspec.yaml.
"""

import re
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
PUBSPEC = ROOT / "pubspec.yaml"
PREVIEWS = ROOT / "assets" / "previews"
DART_OUTPUT = ROOT / "lib" / "data" / "image_previews.dart"

# Twice the largest display size (600 px) for high-density screens.
MAX_SIZE = 1200
JPEG_QUALITY = 82
IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".gif"}
# Images outside the focus folders, with the size of their preview.
EXTRA_IMAGES = {"assets/images/carrosse.png": 160}


def focus_folders():
    """assets/focus/<folder>/ entries of pubspec.yaml."""
    return re.findall(r"^\s*-\s*(assets/focus/[^\s#]+/)\s*$", PUBSPEC.read_text(), re.M)


def make_preview(source: Path, max_size: int):
    """Returns (preview path relative to ROOT, width, height)."""
    relative = source.relative_to(ROOT / "assets")
    with Image.open(source) as image:
        image = ImageOps.exif_transpose(image)
        has_alpha = image.mode in ("RGBA", "LA") or "transparency" in image.info
        image.thumbnail((max_size, max_size), Image.LANCZOS)
        if has_alpha:
            target = (PREVIEWS / relative).with_suffix(".png")
            target.parent.mkdir(parents=True, exist_ok=True)
            # 256-colour palette with alpha: same look as the GIF originals,
            # several times lighter than a full RGBA PNG.
            image.convert("RGBA").quantize(colors=256, method=Image.Quantize.FASTOCTREE).save(
                target, optimize=True)
        else:
            target = (PREVIEWS / relative).with_suffix(".jpg")
            target.parent.mkdir(parents=True, exist_ok=True)
            image.convert("RGB").save(target, quality=JPEG_QUALITY, optimize=True,
                                      progressive=True)
        return target.relative_to(ROOT).as_posix(), image.width, image.height


def update_pubspec(preview_folders):
    """Lists every preview folder in pubspec.yaml (after the last asset line)."""
    text = PUBSPEC.read_text()
    missing = [f for f in preview_folders if not re.search(rf"^\s*-\s*{re.escape(f)}\s*$", text, re.M)]
    if not missing:
        return
    anchor = list(re.finditer(r"^    - assets/[^\n]*\n", text, re.M))[-1]
    lines = "".join(f"    - {folder}\n" for folder in missing)
    PUBSPEC.write_text(text[:anchor.end()] + lines + text[anchor.end():])


def main():
    sources = {}
    for folder in focus_folders():
        for file in sorted((ROOT / folder).iterdir()):
            if file.suffix.lower() in IMAGE_EXTENSIONS:
                sources[file.relative_to(ROOT).as_posix()] = MAX_SIZE
    sources.update(EXTRA_IMAGES)

    entries = {}
    for asset, max_size in sources.items():
        entries[asset] = make_preview(ROOT / asset, max_size)

    lines = [
        "// GENERATED by tool/make_previews.py — do not edit by hand.",
        "",
        "class ImagePreviews {",
        "  /// Original asset -> light preview with its size in pixels.",
        "  static const Map<String, ({String path, int width, int height})> all = {",
    ]
    for asset, (preview, width, height) in sorted(entries.items()):
        lines.append(f'    "{asset}": (path: "{preview}", width: {width}, height: {height}),')
    lines += [
        "  };",
        "",
        "  /// The preview to display for [asset], or the asset itself when it has",
        "  /// none (e.g. an image added without running the tool).",
        "  static String pathOf(String asset) => all[asset]?.path ?? asset;",
        "",
        "  /// Width / height of [asset], known without loading it, or null.",
        "  static double? aspectRatioOf(String asset) {",
        "    final preview = all[asset];",
        "    return preview == null ? null : preview.width / preview.height;",
        "  }",
        "}",
        "",
    ]
    DART_OUTPUT.write_text("\n".join(lines))

    update_pubspec(sorted({str(Path(p).parent.as_posix()) + "/" for p, _, _ in entries.values()}))

    original = sum((ROOT / a).stat().st_size for a in entries)
    previews = sum((ROOT / p).stat().st_size for p, _, _ in entries.values())
    print(f"{len(entries)} previews: {original / 1e6:.1f} MB -> {previews / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
